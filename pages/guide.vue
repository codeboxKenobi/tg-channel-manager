<script setup lang="ts">
// Руководство пользователя: содержание слева (на узких экранах сворачивается) и разделы справа.
const sections = [
  { id: 'start', title: 'Быстрый старт' },
  { id: 'roles', title: 'Роли и доступ' },
  { id: 'bot', title: 'Бот' },
  { id: 'channels', title: 'Каналы' },
  { id: 'parser', title: 'Парсер' },
  { id: 'drafts', title: 'Подготовка постов' },
  { id: 'published', title: 'Опубликованные' },
  { id: 'metrics', title: 'Метрики' },
  { id: 'users', title: 'Пользователи' },
  { id: 'account', title: 'Профиль' },
  { id: 'faq', title: 'Частые вопросы' },
]

const active = ref(sections[0].id)
const tocOpen = ref(false)

let wide: MediaQueryList | null = null
let spy: IntersectionObserver | null = null
const visible = new Set<string>()

const syncToc = () => (tocOpen.value = Boolean(wide?.matches)) // на широком экране содержание всегда раскрыто

function onSummary(e: Event) {
  if (wide?.matches) e.preventDefault() // на широком экране сворачивать содержание нельзя
}

function go(id: string) {
  const el = document.getElementById(id)
  if (!el) return
  const reduce = window.matchMedia('(prefers-reduced-motion: reduce)').matches
  el.scrollIntoView({ behavior: reduce ? 'auto' : 'smooth', block: 'start' })
  history.replaceState(history.state, '', `#${id}`)
  active.value = id
  if (!wide?.matches) tocOpen.value = false
}

// подсвечиваем в содержании раздел, который сейчас читают
function onScroll() {
  const atBottom = window.innerHeight + window.scrollY >= document.documentElement.scrollHeight - 2
  if (atBottom) active.value = sections[sections.length - 1].id
}

onMounted(() => {
  wide = window.matchMedia('(min-width: 981px)')
  syncToc()
  wide.addEventListener('change', syncToc)

  spy = new IntersectionObserver(
    (entries) => {
      for (const e of entries) {
        if (e.isIntersecting) visible.add(e.target.id)
        else visible.delete(e.target.id)
      }
      const first = sections.find((s) => visible.has(s.id))
      if (first) active.value = first.id
    },
    { rootMargin: '-80px 0px -60% 0px' },
  )
  for (const s of sections) {
    const el = document.getElementById(s.id)
    if (el) spy.observe(el)
  }
  window.addEventListener('scroll', onScroll, { passive: true })

  const hash = location.hash.slice(1)
  if (hash && sections.some((s) => s.id === hash)) nextTick(() => go(hash))
})

onBeforeUnmount(() => {
  wide?.removeEventListener('change', syncToc)
  spy?.disconnect()
  window.removeEventListener('scroll', onScroll)
})
</script>

