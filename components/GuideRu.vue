    <h3>Удаление по вашему желанию</h3>
    <ol>
      <li>Откройте <NuxtLink to="/account">«Профиль»</NuxtLink> (имя в правом верхнем углу) и найдите блок «Удаление аккаунта».</li>
      <li>Введите свой пароль и нажмите «Удалить аккаунт».</li>
      <li>Прочитайте предупреждение и подтвердите удаление. После этого вы выйдете из приложения.</li>
    </ol>
    <dl class="defs">
      <dt><span class="badge">Редактор</span></dt>
      <dd>Удаляется только сам аккаунт и его доступ к каналам. Посты, которые вы создали, остаются у администратора.</dd>
      <dt><span class="badge">Администратор</span></dt>
      <dd>Вместе с аккаунтом удаляется всё его пространство: каналы с постами, лайками и статистикой, источники парсера, загруженные картинки, все его редакторы и подключённый бот. Сообщения, которые уже опубликованы в Telegram-каналах, остаются на месте.</dd>
      <dt><span class="badge">Главный администратор</span></dt>
      <dd>Не может удалить аккаунт сам: блока с кнопкой удаления в его профиле нет.</dd>
