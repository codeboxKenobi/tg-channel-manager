    <p class="callout callout-warn">Пароль передан по почте, поэтому после первого входа смените его на странице «Профиль», а письмо удалите.</p>
    <p>Если письмо не удалось отправить, под формой на странице «Пользователи» появится предупреждение. Аккаунт при этом уже создан: передайте логин и пароль другим способом.</p>

    <h3>Если забыли пароль</h3>
    <ol>
      <li>На странице входа нажмите «Забыли пароль?» и введите email своего аккаунта.</li>
