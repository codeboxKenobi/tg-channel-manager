    <h3>Автоматическое удаление при бездействии</h3>
    <p>Если в аккаунт не заходили и не пользовались им 90 дней подряд, он удаляется автоматически. Проверка выполняется раз в сутки, ночью по времени сервера. Активностью считается любая работа в приложении под своим аккаунтом: достаточно войти и открыть любую страницу.</p>
    <ul>
      <li><b>Редактор</b> удаляется, если сам не заходил 90 дней.</li>
      <li><b>Администратор</b> удаляется, только если 90 дней не заходил ни он сам, ни один из его редакторов. Пока кто-то из команды работает в пространстве, оно сохраняется.</li>
    </ul>
    <p class="callout callout-warn">Предупреждение по почте перед удалением не отправляется. Если аккаунт нужен, заходите в него хотя бы раз в 90 дней. Запланированные публикации сами по себе активностью не считаются.</p>
