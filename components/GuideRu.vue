    <h2>Частые вопросы</h2>
    <dl class="faq">
      <dt>Вижу «Бот не подключён»</dt>
      <dd>Администратору нужно добавить токен бота на странице «Бот». Пока бота нет, публикация и сбор статистики не работают.</dd>
      <dt>Пост получил статус «Ошибка публикации»</dt>
      <dd>Прочитайте причину в карточке. Чаще всего бот не добавлен в администраторы канала или у него нет права публиковать сообщения, либо ссылка на файл недоступна. Исправьте это и нажмите «Опубликовать сейчас».</dd>
      <dt>Вижу «Вам пока не назначены каналы»</dt>
      <dd>Попросите администратора выдать вам доступ к каналам на странице «Пользователи».</dd>
      <dt>Пост не ушёл в назначенное время</dt>
      <dd>Проверьте, что канал не отключён на странице «Каналы», а бот остаётся администратором канала. Запланированные посты проверяются каждую минуту.</dd>
      <dt>Не получается добавить канал в парсер</dt>
      <dd>Парсер работает только с публичными каналами, у которых включён просмотр в веб-версии (t.me/s/…). Проверьте @username и доступность канала в браузере.</dd>
      <dt>Текст не помещается в пост</dt>
      <dd>Для текстового поста лимит 4096 символов, для поста с фото или видео — 1024. Сократите текст или уберите медиа.</dd>
      <dt>Мой аккаунт удалили, хотя я его не удалял</dt>
      <dd>Вероятно, в него не заходили 90 дней подряд, и он удалился автоматически. Восстановить его из приложения нельзя: зарегистрируйтесь заново (если регистрация включена) или попросите администратора создать аккаунт. Данные администратора можно вернуть только из резервной копии базы, это может сделать владелец сервера.</dd>
      <dt>В профиле нет кнопки удаления аккаунта</dt>
      <dd>Её нет у главного администратора: он не может удалить аккаунт сам. У остальных блок «Удаление аккаунта» находится внизу страницы «Профиль».</dd>
      <dt>Как переключить язык интерфейса?</dt>
      <dd>Откройте «Профиль» и выберите язык в блоке «Язык интерфейса»: Русский или English. Язык меняется сразу и сохраняется в аккаунте. Подробнее — в разделе «Язык интерфейса».</dd>
      <dt>Часть текста осталась не на моём языке</dt>
      <dd>Названия каналов, заголовки и тексты постов, а также названия источников парсера не переводятся: они остаются такими, как их задали вы или Telegram. Сообщения, которые приходят от самого Telegram, всегда на английском.</dd>
      <dt>Страница входа открылась на другом языке</dt>
      <dd>Страницы входа и регистрации открываются на языке, выбранном в этом браузере в последний раз (по умолчанию на русском). Переключите его кнопками RU и EN над формой. После входа применится язык вашего аккаунта, а если вы выбрали язык вручную, он сохранится в аккаунте.</dd>
      <dt>Забыл пароль</dt>
      <dd>На странице входа нажмите «Забыли пароль?», введите email и код из письма (раздел «Письма и восстановление пароля»). Если такой ссылки нет, попросите администратора сбросить пароль на странице «Пользователи».</dd>
      <dt>Не пришло письмо с кодом или с доступом</dt>
      <dd>Проверьте папку «Спам» и адрес, на который создан аккаунт. Код можно запросить заново не чаще 3 раз в час. Если письма не приходят совсем, сообщите владельцу сервера: у него могут быть не настроены SMTP-параметры.</dd>
    </dl>
